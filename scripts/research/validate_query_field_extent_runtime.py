"""Cold public text entry probes: a worker receives only field and legal query.

Four fixed first queries compare to already sealed atomic-baseline predictions.
No new target labels are read and no performance claim is generated by this test.
"""
import argparse
import subprocess
from pathlib import Path
from unittest.mock import patch
import torch
from radio_gs.query_field.runtime import QueryFieldRuntime
from scripts.research.run_query_field_signed_scope import ROOT as PARENT
from scripts.research.run_query_field_relations import read,write,receipt,check,execute

ROOT=Path('output/query_field_20261012/text_extent_public_v1')
CODE=['radio_gs/query_field/runtime.py','radio_gs/query_field/extent_runtime.py',__file__]


def prepare():
    ROOT.mkdir(parents=True,exist_ok=False);jobs=[]
    for j in read(PARENT/'prediction_config.json')['jobs']:
        p=PARENT/'predictions'/j['name'];r=read(p/'prediction.json')
        check(dict(path=str(p/'predictions.pt'),sha256=r['predictions_sha256']))
        data=torch.load(p/'predictions.pt',weights_only=True)
        fixture=ROOT/'queries'/f"{j['scene']}.pt";fixture.parent.mkdir(parents=True,exist_ok=True)
        torch.save(dict(native_query=data['native_query_vectors'][0],generic_negatives=data['generic_negative_vectors']),fixture)
        jobs.append(dict(scene=j['scene'],field=j['field'],query=receipt(fixture),
            reference=receipt(p/'predictions.pt'),query_index=0,text=data['texts'][0]))
        del data
    write(ROOT/'design.json',dict(jobs=jobs,code=[receipt(p) for p in CODE],scope_rule='atomic',
        query_selection='first recorded query per scene, fixed before execution',
        implementation_commit=subprocess.check_output(['git','rev-parse','HEAD'],text=True).strip(),
        target_labels_used=False,all_queries_validated=False,default_promoted=False))


def design():
    d=read(ROOT/'design.json')
    for r in d['code']:check(r)
    return d


def worker(index):
    d=design();j=d['jobs'][index];check(j['query'])
    packet=torch.load(j['query']['path'],weights_only=True)
    assert set(packet)=={'native_query','generic_negatives'}
    runtime=QueryFieldRuntime.load(j['field']);runtime.prepare_text_extent(scope_device='cuda')
    with patch('builtins.open',side_effect=AssertionError('query IO')),patch('io.open',side_effect=AssertionError('query IO')),patch('torch.load',side_effect=AssertionError('query IO')):
        result=runtime.text_extent(**packet,scope_rule=d['scope_rule'])
    out=ROOT/'probes'/j['scene'];out.mkdir(parents=True,exist_ok=False)
    torch.save(dict(membership=result.membership_scores,selected=result.selected),out/'result.pt')
    write(out/'result.json',dict(scene=j['scene'],query=j['query'],field=j['field'],diagnostics=result.diagnostics,
        output=receipt(out/'result.pt'),cold_load=True,query_file_io_denied=True,
        worker_loaded_reference_predictions=False,os_sandbox=False))


def run(gpu):
    d=design();probes=[]
    for index,j in enumerate(d['jobs']):
        execute(['-m','scripts.research.validate_query_field_extent_runtime','worker','--index',str(index)],
                ROOT/'logs'/f"{j['scene']}.log",gpu)
        r=read(ROOT/'probes'/j['scene']/'result.json');check(r['output']);check(j['reference'])
        actual=torch.load(r['output']['path'],weights_only=True);ref=torch.load(j['reference']['path'],weights_only=True)
        for key,source in [('membership','membership_by_control'),('selected','selected_by_control')]:
            assert torch.equal(actual[key],ref[source]['native_atomic_abstention'][:,0]),(j['scene'],key)
        probes.append(dict(scene=j['scene'],query=j['text'],member_values_exact=True,selected_bits_exact=True,
            record=receipt(ROOT/'probes'/j['scene']/'result.json')))
        print('public cold parity PASS',j['scene'],flush=True);del actual,ref
    result=dict(passed=True,probes=probes,design=receipt(ROOT/'design.json'),target_labels_used=False,
        all_queries_validated=False,whole_five_task=False,default_promoted=False)
    write(ROOT/'audit.json',result);write('docs/experiments/2026-10-12-text-extent-public-audit.json',result)


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('stage',choices=['prepare','worker','run']);p.add_argument('--index',type=int);p.add_argument('--gpu',type=int,default=2)
    a=p.parse_args();torch.set_num_threads(4)
    if a.stage=='prepare':prepare()
    elif a.stage=='worker':worker(a.index)
    else:run(a.gpu)
