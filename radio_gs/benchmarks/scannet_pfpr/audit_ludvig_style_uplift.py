#!/usr/bin/env python3
"""Audit a PFPR direct-DINO cache as a LUDVIG-style sanity baseline.

This intentionally does not call the result a LUDVIG reproduction: official
LUDVIG has no PFPR retrieval adapter, and these caches were generated by the
RADIO-GS scorer rather than the official LUDVIG uplifting implementation.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
from typing import Any, Mapping

from .evaluate_predictions import evaluate


OFFICIAL_LUDVIG_REPOSITORY = "https://github.com/naver/ludvig"
OFFICIAL_LUDVIG_AUDITED_COMMIT = "4461fc515439bb498a75d71738a1e73cf7a452ed"
EXPECTED_METHOD = "official_dino_v3_7b_center3x3_to_canonical_dino_field"
EXPECTED_QUERY_DESCRIPTOR = "official_dino_v3_7b_center_3x3_l2_mean"
EXPECTED_READOUT = (
    "continuous_opacity_weighted_gaussian_convolved_with_5cm_voxel_cell"
)


def _sha256(path: str | Path) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _git_commit(path: str | Path) -> str:
    return subprocess.check_output(
        ["git", "-C", str(Path(path)), "rev-parse", "HEAD"],
        text=True,
    ).strip()


def prediction_set_sha256(prediction_dir: str | Path) -> str:
    """Hash query IDs and vector bytes into one deterministic cache digest."""

    root = Path(prediction_dir)
    paths = sorted(root.glob("*.npy"))
    if not paths:
        raise ValueError("PFPR prediction directory contains no score vectors")
    digest = hashlib.sha256()
    for path in paths:
        digest.update(path.name.encode("utf-8"))
        digest.update(b"\0")
        digest.update(bytes.fromhex(_sha256(path)))
    return digest.hexdigest()


def validate_style_cache(
    benchmark_dir: str | Path,
    prediction_dir: str | Path,
    prediction_report: str | Path,
) -> dict[str, Any]:
    """Validate that a cache is the narrow, learning-free DINO uplift sanity."""

    benchmark_root = Path(benchmark_dir)
    prediction_root = Path(prediction_dir)
    report_path = Path(prediction_report)
    report = json.loads(report_path.read_text(encoding="utf-8"))
    method_manifest = json.loads(
        (benchmark_root / "manifest.method.json").read_text(encoding="utf-8")
    )
    public_manifest = json.loads(
        (benchmark_root / "manifest.public.json").read_text(encoding="utf-8")
    )
    evaluator_manifest = json.loads(
        (benchmark_root / "manifest.evaluator.json").read_text(encoding="utf-8")
    )
    if report.get("benchmark") != "scannet-pfpr-small-v2":
        raise ValueError("LUDVIG-style audit requires the corrected PFPR v2 raster")
    if report.get("method") != EXPECTED_METHOD:
        raise ValueError("cache is not the unadapted direct-DINO uplift baseline")
    protocol = dict(report.get("protocol", {}))
    required = {
        "method_manifest_only": True,
        "evaluator_anchor_opened": False,
        "query_descriptor": EXPECTED_QUERY_DESCRIPTOR,
        "primitive_score": "cosine",
        "feature_calibration": "none",
        "candidate_readout": EXPECTED_READOUT,
        "support_gate_required": False,
        "requires_official_extracted_capability_teachers": True,
    }
    mismatches = {
        key: {"expected": expected, "actual": protocol.get(key)}
        for key, expected in required.items()
        if protocol.get(key) != expected
    }
    if protocol.get("crop_spatial_adapter") is not None:
        mismatches["crop_spatial_adapter"] = {
            "expected": None,
            "actual": protocol.get("crop_spatial_adapter"),
        }
    if protocol.get("crop_context_adapter") is not None:
        mismatches["crop_context_adapter"] = {
            "expected": None,
            "actual": protocol.get("crop_context_adapter"),
        }
    if mismatches:
        raise ValueError(f"PFPR cache is not the frozen style baseline: {mismatches}")
    if method_manifest.get("benchmark_version") != "scannet-pfpr-small-v2":
        raise ValueError("PFPR method manifest is not v2")
    method_queries = list(method_manifest.get("queries", []))
    public_queries = list(public_manifest.get("queries", []))
    private_queries = list(evaluator_manifest.get("queries", []))
    if not method_queries or len(method_queries) != len(private_queries):
        raise ValueError("PFPR method/private manifests do not align")
    private_names = {
        "anchor_world_xyz",
        "pose",
        "depth",
        "mask",
        "instance_id",
        "class_id",
    }
    for query in method_queries:
        if set(query.get("available_method_inputs", ())) != {
            "scene_id",
            "crop_rgb",
        }:
            raise ValueError("method-visible PFPR inputs are not scene_id + crop_rgb")
        if private_names & set(query):
            raise ValueError("method manifest leaks evaluator-private query fields")
    if any("anchor_world_xyz" in query for query in public_queries):
        raise ValueError("public PFPR manifest leaks private anchors")
    if not all("anchor_world_xyz" in query for query in private_queries):
        raise ValueError("private PFPR manifest lacks evaluator anchors")
    scene_reports = list(report.get("scene_reports", []))
    scenes = tuple(sorted(str(item["scene_id"]) for item in scene_reports))
    if not scenes:
        raise ValueError("prediction report has no scenes")
    expected_query_ids = {
        str(query["query_id"])
        for query in method_queries
        if str(query.get("scene_id", "")) in set(scenes)
    }
    prediction_paths = sorted(prediction_root.glob("*.npy"))
    predicted_query_ids = {path.stem for path in prediction_paths}
    if predicted_query_ids != expected_query_ids:
        raise ValueError(
            "PFPR score-vector set does not exactly match the declared scenes"
        )
    return {
        "prediction_report": report,
        "scene_names": scenes,
        "query_count": len(expected_query_ids),
        "full_benchmark_scene_count": len(
            {str(query["scene_id"]) for query in method_queries}
        ),
        "full_benchmark_query_count": len(method_queries),
        "prediction_set_sha256": prediction_set_sha256(prediction_root),
        "prediction_report_sha256": _sha256(report_path),
    }


def _metrics_equal(
    lhs: Mapping[str, Any], rhs: Mapping[str, Any], *, tolerance: float = 1e-12
) -> bool:
    if set(lhs) != set(rhs):
        return False
    return all(abs(float(lhs[key]) - float(rhs[key])) <= tolerance for key in lhs)


def audit(
    benchmark_dir: str | Path,
    prediction_dir: str | Path,
    prediction_report: str | Path,
    output_dir: str | Path,
    *,
    source_results: str | Path | None = None,
    repository_root: str | Path = ".",
) -> dict[str, Any]:
    """Re-evaluate a validated cache and attach honest comparison provenance."""

    validation = validate_style_cache(
        benchmark_dir, prediction_dir, prediction_report
    )
    destination = Path(output_dir)
    destination.mkdir(parents=True, exist_ok=True)
    evaluation = evaluate(
        benchmark_dir,
        prediction_dir,
        destination / "evaluation.json",
        scene_names=tuple(validation["scene_names"]),
    )
    source_check: dict[str, Any] | None = None
    if source_results is not None and Path(source_results).is_file():
        source = json.loads(Path(source_results).read_text(encoding="utf-8"))
        source_check = {
            "path": str(Path(source_results).resolve()),
            "sha256": _sha256(source_results),
            "query_micro_identical": _metrics_equal(
                source["metrics_query_micro"],
                evaluation["metrics_query_micro"],
            ),
            "scene_macro_identical": _metrics_equal(
                source["metrics_scene_macro"],
                evaluation["metrics_scene_macro"],
            ),
        }
        if not all(
            source_check[key]
            for key in ("query_micro_identical", "scene_macro_identical")
        ):
            raise ValueError("re-evaluation does not reproduce saved PFPR metrics")
    scorer_path = (
        Path(repository_root)
        / "radio_gs"
        / "benchmarks"
        / "scannet_pfpr"
        / "score_dino_center.py"
    ).resolve()
    report: dict[str, Any] = {
        "benchmark": "scannet-pfpr-small-v2",
        "result_name": "LUDVIG-style DINO uplift sanity",
        "result_status": "diagnostic_only",
        "official_ludvig_reproduction": False,
        "paper_metric_comparable": False,
        "why_not_official_reproduction": (
            "Official LUDVIG does not define PFPR patch-to-3D point retrieval, "
            "and this score cache was not exported by its official wrapper."
        ),
        "method_visible_input": {
            "fields": ["scene_id", "crop_rgb"],
            "crop_contract": "depth_aligned_RGB_v2_center_128x128",
            "query_pose": False,
            "query_depth": False,
            "query_mask": False,
            "query_class_or_instance": False,
            "private_anchor": False,
        },
        "evaluator_only_private_input": {
            "anchor_world_xyz": True,
            "use": "ranked_candidate_distance_metrics_only",
            "opened_by_score_generator": False,
        },
        "cache_implementation": {
            "generator_family": EXPECTED_METHOD,
            "generator_commit_recorded_in_cache": None,
            "warning": (
                "The historical cache did not record its generator commit; "
                "the audit records immutable cache hashes and the current "
                "implementation only, without retroactively asserting identity."
            ),
            "implementation_entrypoint_at_audit": str(scorer_path),
            "implementation_sha256_at_audit": _sha256(scorer_path),
            "radio_gs_commit_at_audit": _git_commit(repository_root),
            "query_encoder": "C-RADIO official DINOv3-7B spatial adaptor",
            "query_pooling": "center_3x3_L2_mean",
            "field": "RADIO-GS canonical DINO field",
            "uplift_readout": EXPECTED_READOUT,
            "retrieval": "cosine_score_then_10cm_Euclidean_NMS",
            "task_specific_training_or_adapter": False,
        },
        "official_ludvig_reference": {
            "repository": OFFICIAL_LUDVIG_REPOSITORY,
            "audited_commit": OFFICIAL_LUDVIG_AUDITED_COMMIT,
            "supported_tasks": (
                "foreground/background and open-vocabulary segmentation"
            ),
            "feature_encoder": "DINOv2_ViT-g_with_registers",
            "uplift": (
                "multi-view inverse rendering into scene Gaussians with "
                "official rasterizer weights"
            ),
            "default_NVOS_diffusion": "200-NN_graph_100_iterations",
        },
        "material_differences_from_official_ludvig": [
            "PFPR retrieval is not an official LUDVIG task or metric.",
            "C-RADIO DINOv3 adaptor replaces official DINOv2 ViT-g registers.",
            "The canonical MPR field replaces official LUDVIG inverse rendering.",
            "No official LUDVIG graph diffusion or scribble regularizer is used.",
            "The PFPR query is one held-out RGB crop, not scene-view feature maps.",
        ],
        "coverage": {
            "scene_count": len(validation["scene_names"]),
            "query_count": int(validation["query_count"]),
            "full_benchmark_scene_count": int(
                validation["full_benchmark_scene_count"]
            ),
            "full_benchmark_query_count": int(
                validation["full_benchmark_query_count"]
            ),
            "complete": (
                len(validation["scene_names"])
                == int(validation["full_benchmark_scene_count"])
            ),
            "support_gate_required": False,
            "warning": (
                "Partial six-scene, no-support-gate diagnostic; not a formal "
                "20-scene PFPR result."
            ),
        },
        "immutable_cache_provenance": {
            "prediction_set_sha256": validation["prediction_set_sha256"],
            "prediction_report_sha256": validation[
                "prediction_report_sha256"
            ],
        },
        "source_result_reproduction_check": source_check,
        "evaluation": evaluation,
    }
    (destination / "audit.json").write_text(
        json.dumps(report, indent=2), encoding="utf-8"
    )
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--benchmark-dir", required=True)
    parser.add_argument("--prediction-dir", required=True)
    parser.add_argument("--prediction-report", required=True)
    parser.add_argument("--output-dir", required=True)
    parser.add_argument("--source-results", default="")
    parser.add_argument("--repository-root", default=".")
    args = parser.parse_args()
    print(
        json.dumps(
            audit(
                args.benchmark_dir,
                args.prediction_dir,
                args.prediction_report,
                args.output_dir,
                source_results=(
                    args.source_results
                    if str(args.source_results).strip()
                    else None
                ),
                repository_root=args.repository_root,
            ),
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
